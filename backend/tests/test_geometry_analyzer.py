"""Regression tests for the deterministic geometry engine.

These are the tests that matter most in the project: the analyzer's numbers are
the evidence every AI decision cites, so a regression here silently corrupts
everything downstream.

Fixtures (`tests/fixtures/*.stl`) are generated by `tests/fixtures/build.py`
with known ground-truth dimensions, so the assertions below are against real
expected values rather than whatever the code currently happens to produce.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pytest
import trimesh

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.services.geometry.analyzer import (  # noqa: E402
    analyse_file,
    load_mesh,
    score_printability,
    Finding,
)

FIXTURES = Path(__file__).parent / "fixtures"

# Ground truth from tests/fixtures/build.py
CUBE_SIZE_MM = 20.0
CUBE_VOLUME_MM3 = 8000.0
THIN_WALL_MM = 0.28


def _analyse(name: str, **kwargs):
    path = FIXTURES / name
    import hashlib

    sha = hashlib.sha256(path.read_bytes()).hexdigest()
    return analyse_file(str(path), input_sha256=sha, **kwargs)


def test_cube_is_watertight_solid_with_known_volume():
    report = _analyse("cube_20mm.stl")
    metrics = report.metrics

    assert metrics.triangle_count == 12
    assert metrics.dimensions_mm == {"x": 20.0, "y": 20.0, "z": 20.0}
    assert metrics.is_watertight is True
    assert metrics.is_winding_consistent is True
    assert metrics.is_volume is True
    assert metrics.body_count == 1
    assert metrics.euler_number == 2  # genus 0 closed surface
    assert metrics.volume_mm3 == pytest.approx(CUBE_VOLUME_MM3, rel=1e-3)
    assert metrics.surface_area_mm2 == pytest.approx(2400.0, rel=1e-3)
    assert metrics.boundary_edge_count == 0
    assert metrics.non_manifold_edge_count == 0
    assert metrics.degenerate_face_count == 0
    assert metrics.duplicate_vertex_count == 0


def test_cube_facet_loading_merges_vertices():
    """STL stores no shared vertices; loading must weld them.

    Without merging, a 12-triangle cube looks like 12 disconnected bodies and
    reports a non-watertight, zero-volume mesh.
    """
    mesh = load_mesh(str(FIXTURES / "cube_20mm.stl"))
    assert len(mesh.vertices) == 8
    assert mesh.body_count == 1
    assert mesh.volume == pytest.approx(CUBE_VOLUME_MM3, rel=1e-3)


def test_cube_scores_perfectly_with_no_findings():
    report = _analyse("cube_20mm.stl")
    assert report.printability_score == 100.0
    assert report.risk_level == "low"
    assert [f.code for f in report.findings] == []


def test_thin_wall_is_measured_not_guessed():
    """The headline feature: measure a real 0.28 mm wall by ray casting."""
    report = _analyse("thin_wall.stl", no_opening_mm=0.4)
    metrics = report.metrics

    assert metrics.is_watertight is True
    assert metrics.estimated_min_wall_mm == pytest.approx(THIN_WALL_MM, abs=0.03)

    wall_findings = [f for f in report.findings if f.code == "THIN_WALL"]
    assert len(wall_findings) == 1
    finding = wall_findings[0]
    assert finding.severity == "critical"
    assert finding.measured_value == pytest.approx(THIN_WALL_MM, abs=0.03)
    # Two extrusion lines with a 0.4 mm nozzle.
    assert finding.limit_value == pytest.approx(0.8, abs=1e-6)
    assert finding.unit == "mm"


def test_thin_wall_is_acceptable_with_a_large_nozzle():
    """0.28 mm is unprintable at 0.4 mm but the limit is nozzle-derived."""
    tight = _analyse("thin_wall.stl", no_opening_mm=0.4)
    loose = _analyse("thin_wall.stl", no_opening_mm=0.2)
    assert any(f.code == "THIN_WALL" for f in tight.findings)
    # 2 x 0.2 = 0.4 mm, still above a 0.28 mm wall, so the finding persists.
    assert any(f.code == "THIN_WALL" for f in loose.findings)


def test_open_mesh_is_detected_as_not_watertight():
    report = _analyse("open_mesh.stl")
    metrics = report.metrics

    assert metrics.is_watertight is False
    assert metrics.boundary_edge_count > 0
    assert metrics.volume_mm3 is None

    codes = [f.code for f in report.findings]
    assert "MESH_NOT_WATERTIGHT" in codes
    assert report.risk_level == "high"


def test_overhang_angle_is_measured_from_face_normals():
    report = _analyse("overhang_60deg.stl", max_overhang_deg=45.0)
    metrics = report.metrics

    # A box rotated 60 degrees about Y has 60-degree downward faces.
    assert metrics.worst_overhang_deg == pytest.approx(60.0, abs=0.5)
    assert metrics.overhang_face_count > 0
    assert metrics.overhang_area_mm2 > 0
    assert any(f.code == "OVERHANGS" for f in report.findings)


def test_bed_contact_is_not_counted_as_overhang():
    """A cube's underside is downward-facing but supported by the plate."""
    report = _analyse("cube_20mm.stl")
    assert report.metrics.overhang_face_count == 0
    assert report.metrics.overhang_area_mm2 == 0.0
    assert report.metrics.worst_overhang_deg == 0.0


def test_solid_box_reports_no_false_thin_wall():
    """A 20 mm solid block is not a thin-wall problem."""
    report = _analyse("cube_20mm.stl", no_opening_mm=0.4)
    assert report.metrics.estimated_min_wall_mm == pytest.approx(20.0, abs=0.05)
    assert not any(f.code == "THIN_WALL" for f in report.findings)


def test_score_is_deterministic_and_transparent():
    first = _analyse("open_mesh.stl").to_dict()
    second = _analyse("open_mesh.stl").to_dict()
    assert first == second

    breakdown = first["score_breakdown"]
    assert breakdown["base_score"] == 100.0
    assert "method" in breakdown
    assert breakdown["counts_by_severity"]["critical"] >= 1
    # The penalty must equal the sum of the listed contributions.
    contributions = sum(item["penalty"] for item in breakdown["contributors"])
    assert breakdown["penalty_total"] == pytest.approx(contributions)
    assert first["printability_score"] == pytest.approx(100.0 - contributions)


def test_score_cannot_go_negative():
    findings = [Finding(code="X", severity="critical", message="x") for _ in range(10)]
    metrics = _analyse("open_mesh.stl").metrics
    score, risk, _ = score_printability(findings, metrics)
    assert score == 0.0
    assert risk == "high"


def test_info_findings_do_not_reduce_the_score():
    metrics = _analyse("cube_20mm.stl").metrics
    score_with_info, _, _ = score_printability(
        [Finding(code="LOW_DENSITY", severity="info", message="opportunity")], metrics
    )
    assert score_with_info == 100.0


def test_analysis_handles_a_multi_body_file():
    """Two separated cubes: 2 bodies, both closed, combined volume is valid.

    `is_watertight` is evaluated per connected component, so a file of two
    closed shells is still watertight overall. `body_count` is what reveals
    that the "part" is actually two pieces.
    """
    two = trimesh.util.concatenate(
        [
            trimesh.creation.box(extents=(10, 10, 10)),
            trimesh.creation.box(extents=(10, 10, 10)).apply_translation([30, 0, 0]),
        ]
    )
    path = FIXTURES / "_tmp_multibody.stl"
    two.export(path)
    try:
        import hashlib

        report = analyse_file(
            str(path), input_sha256=hashlib.sha256(path.read_bytes()).hexdigest()
        )
        assert report.metrics.body_count == 2
        assert report.metrics.is_watertight is True
        assert report.metrics.volume_mm3 == pytest.approx(2000.0, rel=1e-3)
        assert any(f.code == "MULTI_BODY" for f in report.findings)
    finally:
        path.unlink(missing_ok=True)


def test_load_mesh_rejects_a_file_with_no_faces():
    empty = FIXTURES / "_tmp_empty.stl"
    empty.write_bytes(b"solid empty\nendsolid empty\n")
    try:
        with pytest.raises(ValueError):
            load_mesh(str(empty))
    finally:
        empty.unlink(missing_ok=True)


def test_all_fixture_regression_models_load_and_analyse():
    """Every regression model must survive the full pipeline."""
    models = sorted(FIXTURES.glob("*.stl"))
    assert len(models) >= 4, "expected the standard regression suite"
    for path in models:
        import hashlib

        report = analyse_file(
            str(path), input_sha256=hashlib.sha256(path.read_bytes()).hexdigest()
        )
        assert report.metrics.triangle_count > 0
        assert 0.0 <= report.printability_score <= 100.0
        assert report.risk_level in {"low", "medium", "high"}
        assert report.metrics.dimensions_mm["x"] > 0
